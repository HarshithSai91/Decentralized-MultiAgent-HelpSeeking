def e3():
    name = "E3_abrupt_change"
    if not available(name):
        return
    df, pts, algos = runs(name), points_of(name), algos_of(name)
    KEY["E3"] = {}
    rows_tex, rows_md = [], []
    learners = [a for a in algos if a in ("Greedy", "D-UCB", "D-TS")]
    oracles = [a for a in algos if a not in learners]
    # oracles do not depend on gamma -> report once (point 0)
    for a in oracles:
        st = {m: stat(df, a, 0, m) for m in ("adaptation_latency", "pre_change_regret", "post_change_regret",
                                             "post_change_utility", "post_change_optimal_teammate_rate")}
        lat = cell(df, a, 0, "adaptation_latency")
        cens = int(cell(df, a, 0, "adaptation_censored").sum())
        st["latency_median"] = float(np.median(lat))
        st["n_censored"] = cens
        KEY["E3"].setdefault("oracles", {})[a] = st
        rows_tex.append(" & ".join(["all", SHORT.get(a, a), _lat_tex(st), tex_ci(st["pre_change_regret"], 1),
                                    tex_ci(st["post_change_regret"], 1), tex_ci(st["post_change_utility"], 3),
                                    tex_ci(st["post_change_optimal_teammate_rate"], 1, True)]) + r" \\")
        rows_md.append(["all", a, _lat_md(st), fmt_ci(st["pre_change_regret"], 1), fmt_ci(st["post_change_regret"], 1),
                        fmt_ci(st["post_change_utility"], 3), fmt_ci(st["post_change_optimal_teammate_rate"], 1, True)])
    rows_tex.append("\\midrule")
    for p in pts:
        first = True
        for a in learners:
            st = {m: stat(df, a, p["index"], m) for m in
                  ("adaptation_latency", "pre_change_regret", "post_change_regret", "post_change_utility",
                   "post_change_optimal_teammate_rate", "cumulative_regret", "post_change_ask_rate")}
            lat = cell(df, a, p["index"], "adaptation_latency")
            st["latency_median"] = float(np.median(lat))
            st["latency_q25"], st["latency_q75"] = (float(np.percentile(lat, 25)), float(np.percentile(lat, 75)))
            st["n_censored"] = int(cell(df, a, p["index"], "adaptation_censored").sum())
            KEY["E3"].setdefault(p["label"], {})[a] = st
            lab = f"\\multirow{{{len(learners)}}}{{*}}{{{p['value']}}}" if first else ""
            first = False
            rows_tex.append(" & ".join([lab, SHORT.get(a, a), _lat_tex(st), tex_ci(st["pre_change_regret"], 1),
                                        tex_ci(st["post_change_regret"], 1), tex_ci(st["post_change_utility"], 3),
                                        tex_ci(st["post_change_optimal_teammate_rate"], 1, True)]) + r" \\")
            rows_md.append([p["label"], a, _lat_md(st), fmt_ci(st["pre_change_regret"], 1),
                            fmt_ci(st["post_change_regret"], 1), fmt_ci(st["post_change_utility"], 3),
                            fmt_ci(st["post_change_optimal_teammate_rate"], 1, True)])
        rows_tex.append("\\midrule")
    rows_tex = rows_tex[:-1]
    write_tex("e3_table.tex",
              "\\begin{tabular}{llrrrrr}\n\\toprule\n"
              "$\\gamma$ & Method & $\\tau_{\\mathrm{adapt}}$ median [mean] & Regret $t\\le\\tau$ & Regret $t>\\tau$ & "
              "Utility $t>\\tau$ & Opt.\\ teammate $t>\\tau$ (\\%) \\\\\n\\midrule\n"
              + "\n".join(rows_tex) + "\n\\bottomrule\n\\end{tabular}\n")
    MD.extend(["## E3 — abrupt change at τ = 1000 (varying γ)", "",
               "τ_adapt: rounds after τ until the newly optimal action is chosen in >50% of the trailing 50 rounds "
               "(oracle floor = 26; censored runs count as 1000).", ""])
    MD.extend(md_table(["γ", "Method", "τ_adapt median [mean] (censored)", "Regret t≤τ", "Regret t>τ",
                        "Utility t>τ", "Opt. teammate t>τ %"], rows_md))
    MD.append("")
    # H3 evidence: discounted vs gamma = 1
    MD.extend(["**H3 evidence (paired τ_adapt difference, γ<1 minus γ=1; negative = faster):**", ""])
    h3 = {}
    g1 = [p for p in pts if p["value"] == 1.0][0]["index"]
    for a in learners:
        for p in pts:
            if p["index"] == g1:
                continue
            d = paired(df, a, a, p["index"], "adaptation_latency", point_b=g1)
            dr = paired(df, a, a, p["index"], "post_change_regret", point_b=g1)
            h3[f"{a} {p['label']}"] = {"latency": d, "post_regret": dr}
            MD.append(f"- {a} {p['label']}: Δτ_adapt {fmt_ci(d, 1)}; Δpost-change regret {fmt_ci(dr, 1)}")
    KEY["E3"]["H3"] = h3
    MD.append("")


def _lat_tex(st):
    cens = st.get("n_censored", 0)
    extra = f"$^{{({cens})}}$" if cens else ""
    return f"{st['latency_median']:.0f} [{st['adaptation_latency']['mean']:.0f}]{extra}"


def _lat_md(st):
    cens = st.get("n_censored", 0)
    return f"{st['latency_median']:.0f} [{st['adaptation_latency']['mean']:.0f}]" + (f" ({cens} cens.)" if cens else "")


