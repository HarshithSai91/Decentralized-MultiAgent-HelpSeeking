def e2():
    name = "E2_when_to_ask"
    if not available(name):
        return
    df, pts, algos = runs(name), points_of(name), algos_of(name)
    KEY["E2"] = {}
    rows_tex, rows_md = [], []
    for p in pts:
        first = True
        for a in algos:
            st = {m: stat(df, a, p["index"], m) for m in
                  ("ask_rate", "ask_accuracy", "average_net_utility", "communication_cost",
                   "cumulative_regret", "optimal_teammate_rate")}
            KEY["E2"].setdefault(p["label"], {})[a] = st
            lab = f"\\multirow{{{len(algos)}}}{{*}}{{{p['value']:.2f}}}" if first else ""
            first = False
            rows_tex.append(" & ".join([lab, SHORT.get(a, a), tex_ci(st["ask_rate"], 1, True),
                                        tex_ci(st["ask_accuracy"], 1, True),
                                        tex_ci(st["average_net_utility"], 3),
                                        tex_ci(st["communication_cost"], 1),
                                        tex_ci(st["cumulative_regret"], 1)]) + r" \\")
            rows_md.append([p["label"], a, fmt_ci(st["ask_rate"], 1, True), fmt_ci(st["ask_accuracy"], 1, True),
                            fmt_ci(st["average_net_utility"], 3), fmt_ci(st["communication_cost"], 1),
                            fmt_ci(st["cumulative_regret"], 1)])
        rows_tex.append("\\midrule")
    rows_tex = rows_tex[:-1]
    write_tex("e2_table.tex",
              "\\begin{tabular}{llrrrrr}\n\\toprule\n"
              "$U^{\\mathrm{self}}$ & Method & Ask rate (\\%) & Acc$_{\\mathrm{ask}}$ (\\%) & Avg.\\ utility & Comm.\\ cost & Regret \\\\\n"
              "\\midrule\n" + "\n".join(rows_tex) + "\n\\bottomrule\n\\end{tabular}\n")
    MD.extend(["## E2 — when to ask (varying U_self)", ""])
    MD.extend(md_table(["U_self", "Method", "Ask %", "Acc_ask %", "Avg utility", "Comm. cost", "Regret"], rows_md))
    MD.append("")
    # H5 evidence
    MD.extend(["**H5 evidence:**", ""])
    h5 = {}
    for p in pts:
        for lrn in ("D-UCB", "D-TS"):
            acc = stat(df, lrn, p["index"], "ask_accuracy")
            du_aa = paired(df, lrn, "Always-Ask + Empirical Greedy", p["index"], "average_net_utility")
            du_na = paired(df, lrn, "Never-Ask", p["index"], "average_net_utility")
            dc_aa = paired(df, lrn, "Always-Ask + Empirical Greedy", p["index"], "communication_cost")
            h5[f"{lrn} @ {p['label']}"] = {"acc": acc, "dU_vs_always": du_aa, "dU_vs_never": du_na,
                                            "dCost_vs_always": dc_aa}
            MD.append(f"- {p['label']} {lrn}: Acc_ask {fmt_ci(acc, 1, True)}%; "
                      f"Δutility vs Always-Ask {fmt_ci(du_aa, 3)}; vs Never-Ask {fmt_ci(du_na, 3)}; "
                      f"Δcomm-cost vs Always-Ask {fmt_ci(dc_aa, 1)}")
    KEY["E2"]["H5"] = h5
    MD.append("")


