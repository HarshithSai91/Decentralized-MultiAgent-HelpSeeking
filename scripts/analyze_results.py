#!/usr/bin/env python3
"""Aggregate saved runs into tables (LaTeX + Markdown) and hypothesis evidence.

Reads   results/raw/<exp>/runs.csv           (one row per run)
Writes  results/processed/key_numbers.json  (every number quoted in the report)
        results/RESULTS_SUMMARY.md          (human-readable tables + H1-H5 evidence)
        report/tables/*.tex                 (tables \\input by the LaTeX report)

All intervals are 95% t-intervals over 30 independent seeds; comparisons
between methods are seed-paired (paired by seed).
"""
import json
import os

import numpy as np

from _common import available, cell, fmt, fmt_ci, manifest, paired, runs, stat

TABLE_DIR = os.path.join("report", "tables")
os.makedirs(TABLE_DIR, exist_ok=True)
KEY: dict = {}
MD: list[str] = ["# Results summary", "",
                 "Generated by `scripts/analyze_results.py` from `results/raw/*/runs.csv`. "
                 "Values are mean ± 95% CI half-width over 30 seeds (T = 2000). "
                 "Paired differences use the same seeds (paired by seed).", ""]

SHORT = {
    "Stationary Oracle": "Oracle", "Dynamic Oracle": "Oracle",
    "Initial-Knowledge Oracle": "Init.-Knowl. Oracle",
    "Always-Ask + Random": "Always-Ask + Random",
    "Always-Ask + Fixed-Cheapest": "Always-Ask + Fixed-Cheapest",
    "Always-Ask + Empirical Greedy": "Always-Ask + Greedy ($\\gamma{=}1$)",
    "Never-Ask": "Never-Ask", "Greedy": "D-Greedy", "Greedy (extra)": "D-Greedy$^\\dagger$",
    "D-UCB": "D-UCB", "D-TS": "D-TS",
}


def tex_ci(s, nd=1, pct=False):
    if s["n"] == 0 or np.isnan(s["mean"]):
        return "--"
    k = 100.0 if pct else 1.0
    half = 0.0 if np.isnan(s["ci_high"]) else (s["ci_high"] - s["mean"]) * k
    if half < 0.5 * 10 ** (-nd):
        return f"{s['mean'] * k:.{nd}f}"
    return f"{s['mean'] * k:.{nd}f}{{\\scriptsize$\\pm${half:.{nd}f}}}"


def write_tex(name, body):
    with open(os.path.join(TABLE_DIR, name), "w", encoding="utf-8") as fh:
        fh.write(body)


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def points_of(name):
    return manifest(name)["points"]


def algos_of(name):
    return [a["label"] for a in manifest(name)["algorithms"]]


# =============================================================== E1
def e1():
    name = "E1_stationary"
    if not available(name):
        return
    df, pts, algos = runs(name), points_of(name), algos_of(name)
    KEY["E1"] = {}
    rows_tex, rows_md = [], []
    for a in algos:
        r_tex = [SHORT.get(a, a)]
        r_md = [a]
        for p in pts:
            s = stat(df, a, p["index"], "cumulative_regret")
            o = stat(df, a, p["index"], "optimal_teammate_rate")
            KEY["E1"].setdefault(a, {})[p["label"]] = {
                "regret": s, "opt_teammate": o,
                "utility": stat(df, a, p["index"], "average_net_utility"),
                "ask_rate": stat(df, a, p["index"], "ask_rate"),
                "mae": stat(df, a, p["index"], "mae_theta"),
                "mae_final": stat(df, a, p["index"], "mae_theta_final")}
            r_tex += [tex_ci(s, 1), tex_ci(o, 0, pct=True)]
            r_md += [fmt_ci(s, 1), fmt_ci(o, 0, pct=True)]
        rows_tex.append(" & ".join(r_tex) + r" \\")
        rows_md.append(r_md)
    head = " & ".join(f"\\multicolumn{{2}}{{c}}{{$\\Delta={p['value']:.2f}$}}" for p in pts)
    sub = " & ".join(["Regret & Opt.\\,\\%"] * len(pts))
    write_tex("e1_table.tex",
              "\\begin{tabular}{l" + "rr" * len(pts) + "}\n\\toprule\n"
              f"Method & {head} \\\\\n" + "".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(pts)))
              + f"\n & {sub} \\\\\n\\midrule\n" + "\n".join(rows_tex) + "\n\\bottomrule\n\\end{tabular}\n")
    MD.extend(["## E1 — stationary learning (whom to ask)", "",
               "Cumulative pseudo-regret and optimal-teammate selection rate (% of asks).", ""])
    MD.extend(md_table(["Method"] + [f"{p['label']} {m}" for p in pts for m in ("regret", "opt %")], rows_md))
    MD.append("")

    # H1 evidence: learners vs non-adaptive baselines, paired
    MD.extend(["**H1 evidence (paired regret differences, learner − baseline; negative = learner better):**", ""])
    h1 = {}
    for p in pts:
        for lrn in ("D-UCB", "D-TS"):
            for base in ("Always-Ask + Random", "Always-Ask + Fixed-Cheapest"):
                d = paired(df, lrn, base, p["index"], "cumulative_regret")
                h1[f"{lrn} vs {base} @ {p['label']}"] = d
                MD.append(f"- {p['label']}: {lrn} − {base}: {fmt_ci(d, 1)}")
    KEY["E1"]["H1_paired"] = h1
    # margin vs Delta
    margins = {p["label"]: paired(df, "Always-Ask + Random", "D-TS", p["index"], "cumulative_regret")
               for p in pts}
    KEY["E1"]["margin_random_minus_dts"] = margins
    MD.append("")


